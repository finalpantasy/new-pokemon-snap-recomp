def nvn_phase(name):
    s = name[3:]
    if s in P0:
        return 0
    if s in P1 or s.startswith(STATE_P1):
        return 1
    return 2


# ---------------------------------------------------------------- import classification
def service_of(name, dem, group):
    if group == 'nvn':
        return 'nvn'
    if group in ('libc', 'libc++'):
        if group == 'libc++' and re.match(r'__cxa|_Unwind|__gxx', name):
            return 'libc++abi'
        return group
    m = re.search(r'\bnn::(\w+)::', dem or '')
    if m:
        return m.group(1)
    m = re.match(r'nn(socket|ssl|os|detail|Result)', name)
    if m:
        return {'detail': 'diag', 'Result': 'result'}.get(m.group(1), m.group(1))
    if dem and dem.startswith('nv::'):
        return 'nv'
    if 'vdk_compute' in (dem or ''):
        return 'vdk'
    if name.startswith('_ZTv0') or name.startswith('_ZTh'):
        return 'libc++'
    return 'other'


HARD_OS = re.compile(r'CreateThread|DestroyThread|StartThread|WaitThread|SetThreadCoreMask|GetThreadCoreMask|ChangeThreadPriority|Fiber|GetCurrentCoreNumber')
MOD_OS = re.compile(r'Tls|ThreadPriority|SetThreadName|GetCurrentThread|GetThreadId|YieldThread|SleepThread')
SYNC_OS = re.compile(r'Mutex|Event|Semaphore|ConditionVariable|Timer|SystemEvent')


def difficulty(name, dem, svc, group):
    d = dem or name
    if svc == 'os':
        if HARD_OS.search(d) or re.search(r'nnos(Create|Destroy|Start|Wait|SetThreadCore|GetThreadCore)', name):
            return 'hard', 'Horizon thread/fiber/TLS semantics (priorities, 3 virtual cores, guest ThreadType)'
        if MOD_OS.search(d) or re.search(r'nnos(SetThreadName|GetThread|GetCurrentThread|SleepThread)', name):
            return 'moderate', 'thread-local/identity/sleep semantics over the guest ThreadType and the Horizon scheduler'
        if SYNC_OS.search(d) or re.search(r'nnos.*(Mutex|Event)', name):
            return 'moderate', 'sync primitive living in guest memory (MutexType/EventType layout, priority-aware wake order)'
        if re.search(r'Memory|Address', d):
            return 'moderate', 'virtual-memory API (address-space reservation)'
        return 'trivial', 'tick/random/args'
    if svc in ('account', 'pctl', 'friends', 'nsd', 'err', 'settings', 'prepo', 'ngc', 'album', 'diag', 'result', 'nifm', 'ssl', 'socket', 'time'):
        if svc == 'time':
            return 'trivial', 'host wall clock plus fixed zone'
        if svc in ('diag', 'result', 'err'):
            return 'trivial', 'log/abort or Result bit helpers'
        return 'trivial', 'offline stub (return not-available / success without side effects)'
    if svc == 'util':
        return 'trivial', 'SDK math/string helper or constant table (data import)'
    if svc == 'oe':
        return 'trivial' if re.search(r'GetOperationMode|GetPerformanceMode|SetPerformance|SetResume|Initialize|Notification|Focus', d) else 'moderate', 'applet/oe state, notification-message queue'
    if svc == 'fs':
        return 'moderate', 'ROM mount, save data, file API on host paths (return codes must be Horizon Results)'
    if svc == 'hid':
        return 'moderate', 'npad/touch/keyboard state structs (guest layout) from host input'
    if svc == 'vi':
        return 'moderate', 'display/layer handles, vsync event tied to present'
    if svc == 'nv':
        return 'moderate', 'graphics allocator callbacks and nv init: NVN is replaced, but allocator contract must be kept'
    if svc == 'audio':
        return 'hard', 'audio renderer (audren) mixing semantics, voice/mempool/effect structs, audio thread cadence'
    if svc == 'codec':
        return 'moderate', 'Opus decode via host libopus'
    if svc == 'image':
        return 'moderate', 'JPEG encode/decode (host libjpeg), guest decoder/encoder object layout'
    if svc == 'crypto':
        return 'moderate', 'AES-CBC/SHA/CMAC via host crypto; guest context layouts'
    if svc == 'fontll':
        return 'hard', 'SDK scalable-font engine; needs a faithful reimplementation or lifting of that module'
    if svc == 'swkbd':
        return 'moderate', 'software keyboard applet; stub returns cancel, real UI later'
    if svc == 'mem':
        return 'moderate', 'StandardAllocator over a guest heap block; must match exact-fit/aligned semantics'
    if svc == 'ssl':
        return 'trivial', 'offline stub'
    if svc == 'libc++abi':
        if re.match(r'__cxa_(throw|rethrow|begin_catch|end_catch|allocate_exception|free_exception|call_unexpected)|_Unwind', name):
            return 'hard', 'C++ exception unwinding through lifted frames (.eh_frame/LSDA personality)'
        if name.startswith('__cxa_guard'):
            return 'moderate', 'thread-safe static init guard (guest word, acquire/release semantics)'
        return 'trivial', 'abi stub'
    if svc == 'libc':
        if re.match(r'(setjmp|longjmp)$', name):
            return 'hard', 'jmp_buf over lifted frames (Lua error path)'
        if re.match(r'(wmem|wcs)', name):
            return 'moderate', 'wchar_t is 32-bit on the guest (char32_t on host)'
        if name in ('strtol', 'strtoul', 'strtoull', 'ffsl'):
            return 'moderate', 'long is 64-bit on the guest (host long is 32-bit on Windows): use int64 explicitly'
        if name in ('rand', 'srand'):
            return 'moderate', 'musl LCG sequence differs from host CRT; reproduce musl if the game depends on the sequence'
        if re.match(r'(v?f?s?n?printf|sscanf|fprintf|printf)$', name):
            return 'moderate', 'AAPCS64 va_list and LP64 %ld/%zu/%p vs host CRT'
        if name.startswith('pthread') or name in ('__errno_location', 'getc', 'ungetc', 'fopen', 'fread', 'fwrite', 'fclose', 'feof', 'ferror', 'freopen', 'fputc', 'fputs', 'fgets', 'write', 'stdin', 'stdout', 'stderr', 'localeconv', 'strcoll', 'strftime', 'mktime', 'gmtime', 'time', 'gettimeofday', 'qsort', 'bsearch', 'getenv', 'strerror', 'exit', 'at_quick_exit', 'memalign'):
            return 'moderate', 'guest struct layout or guest callback (musl FILE/tm/jmp ABI)'
        return 'trivial', 'maps to host CRT / musl-equivalent'
    if svc == 'libc++':
        if re.search(r'locale|ios_base|streambuf|ostream|istream|iostream|ctype|collate|regex|future|assoc_sub|exception_ptr|random_device|chrono|thread', d):
            return 'moderate', 'libc++ object with guest layout / global state (locale, streams)'
        if re.search(r'mutex|condition_variable|shared_mutex|shared_weak_count', d):
            return 'moderate', 'libc++ sync object over guest layout (pthread-free impl needed)'
        return 'moderate' if re.search(r'string|stoi|stol|stof|to_string|wstring', d) else 'trivial', 'libc++ std:: type, guest object layout must match'
    return 'moderate', 'unclassified'


def main():
    set_lowprio()
    ap = argparse.ArgumentParser()
    ap.add_argument('--pkl', required=True)
    a = ap.parse_args()
    R = pickle.load(open(a.pkl, 'rb'))
    ev = R['events']
    funcs = R['funcs']
    allvars = R['allvars']
    img = Image()
    rel = load_relocs()
    os.makedirs(OUT, exist_ok=True)

    # ---------- call graphs
    t1 = defaultdict(list)  # f -> [(site, kind, target_or_import_name)] in site order
    for f, e in ev.items():
        items = []
        for pc, tf, k, t in e['calls']:
            if tf is not None:
                items.append((pc, 'f', tf))
        for pc, n, k in e['plt']:
            items.append((pc, 'i', n))
        for pc, n, called in e['imp_ld']:
            items.append((pc, 'ig' if called else 'il', n))
        items.sort()
        t1[f] = items
    rev = defaultdict(set)
    for f, items in t1.items():
        for pc, k, t in items:
            if k == 'f':
                rev[t].add(f)
    fset = {f[0] for f in funcs}
    # function pointers listed in data relocations referenced by init_array
    init_arr = []
    for off in range(0xccb2d8, 0xccb2d8 + 0x618, 8):
        r = rel.get(off)
        if r and r[0] == 'RELATIVE':
            init_arr.append(r[2])
    roots = [('DT_INIT', 0x30)] + [('init_array[%d]' % i, x) for i, x in enumerate(init_arr)] + [('nninitStartup', 0x4e3eb0), ('nnMain', 0x4e3f70)]
    print('roots', len(roots), file=sys.stderr)

    # ---------- tier 1 DFS (direct bl/b only), import first-encounter order
    seen = {}
    order = []  # (kind, name, via_func, depth, root)
    imp_first = {}
    imp_reach1 = Counter()
    depth_of = {}
    sys.setrecursionlimit(1000000)
    for rname, rf in roots:
        if rf not in fset:
            print('root not a function', rname, hex(rf), file=sys.stderr)
            continue
        stack = [(rf, 0)]
        while stack:
            f, d = stack.pop()
            if f in seen:
                continue
            seen[f] = (rname, d)
            order.append(f)
            # push in reverse so that earlier call sites are visited first
            kids = []
            for pc, k, t in t1.get(f, []):
                if k in ('i', 'ig'):
                    if t not in imp_first:
                        imp_first[t] = (len(imp_first), f, d, rname, pc)
                    imp_reach1[t] += 1
                elif k == 'f':
                    kids.append((t, d + 1))
            for kd in reversed(kids):
                stack.append(kd)
    print('tier1 reachable funcs', len(seen), 'imports', len(imp_first), file=sys.stderr)
    # DFS order assigned at pop time already: recompute import order properly (first encounter in visit order)
    imp_first = {}
    for f in order:
        rname, d = seen[f]
        for pc, k, t in t1.get(f, []):
            if k in ('i', 'ig') and t not in imp_first:
                imp_first[t] = (len(imp_first) + 1, f, d, rname, pc)
    # ---------- tier 2: BFS over bl/b + address-taken functions + vtable slots (over-approximate)
    vt_slots = R['vt_slots']
    vt_funcs = {sl0: [x for x in sl if x in fset] for sl0, sl in vt_slots.items()}
    t2 = {}
    for f, e in ev.items():
        items = list(t1.get(f, []))
        for tgt, pc in e['taken'].items():
            items.append((pc, 'f2', tgt))
        for v, pc in e['vt'].items():
            for x in vt_funcs.get(v, []):
                items.append((pc, 'f2', x))
        items.sort(key=lambda x: x[0])
        t2[f] = items
    seen2 = {}
    imp2 = {}
    level = [(rf, rn) for rn, rf in roots if rf in fset]
    for rf, rn in level:
        seen2.setdefault(rf, (rn, 0))
    lv = 0
    while level:
        nxt = []
        for f, rn in level:
            for pc, k, t in t2.get(f, []):
                if k in ('i', 'ig'):
                    if t not in imp2:
                        imp2[t] = (lv, len(imp2) + 1, f)
                elif k in ('f', 'f2') and t in fset and t not in seen2:
                    seen2[t] = (rn, lv + 1)
                    nxt.append((t, rn))
        level = nxt
        lv += 1
    print('tier2 reachable funcs', len(seen2), 'imports', len(imp2), 'levels', lv, file=sys.stderr)

    # ================= NVN =================
    proc_rows = tsv('nvn_procs.tsv')
    str_xrefs = Counter(r['string'] for r in proc_rows)
    cat_funcs = defaultdict(set)
    for r in tsv('render_passes.tsv'):
        if r['function']:
            cat_funcs[r['category']].add(hx(r['function']))
    # descent from pass-string functions, depth 4, direct calls only
    func_cats = defaultdict(set)
    for cat, fs_ in cat_funcs.items():
        for f0 in fs_:
            frontier = {f0}
            visited = {f0}
            for dpt in range(5):
                for f in frontier:
                    func_cats[f].add(cat)
                nf = set()
                for f in frontier:
                    for pc, k, t in t1.get(f, []):
                        if k == 'f' and t not in visited:
                            visited.add(t)
                            nf.add(t)
                frontier = nf
    procs = R['procs']
    per = {}
    callers = defaultdict(Counter)
    loads = defaultdict(Counter)
    for f, e in ev.items():
        for pc, v in e['nvn']:
            callers[allvars[v][1]][f] += 1
        for pc, v in e['nvn_ld']:
            loads[allvars[v][1]][f] += 1
    names = sorted(procs)
    # order = loader order (by B var address)
    names.sort(key=lambda n: procs[n]['B'])
    rows = []
    for n in names:
        p = procs[n]
        sub, grp = nvn_object(n)
        c = callers[n]
        ld = loads[n]
        ctx = Counter()
        for f in set(c) | set(ld):
            for cat in func_cats.get(f, ()):
                ctx[cat] += 1
        used = bool(ld)
        ph = nvn_phase(n) if used else 9
        boot = any(f in seen2 for f in set(c) | set(ld))
        rows.append(dict(proc=n, group=grp, sub=sub, phase=ph, calls=sum(c.values()), loads=sum(ld.values()),
                         nfuncs=len(set(c) | set(ld)),
                         callers=';'.join('%#x:%d' % (f, k) for f, k in sorted(set(c.items()) | set((f, 0) for f in ld if f not in c))[:12]),
                         ctx=','.join(k for k, _ in ctx.most_common(6)),
                         reach=('yes' if boot else 'no') if used else '', varB='%#x' % p['B'], gotvarA='%#x' % p['A'],
                         loader_str_xrefs=str_xrefs.get(n, 0)))
    with open(os.path.join(OUT, 'nvn_usage.tsv'), 'w', encoding='utf-8', newline='\n') as fo:
        fo.write('# file: nvn_usage.tsv\n# one row per NVN proc resolved by loaders 0x254c40 (A: GOT-indirect var) and 0x90a0c0 (B: .bss var from 0x1488db0), in loader order\n')
        fo.write('# calls = loads of the B var followed by blr (register tracker); loads = every ldr of the B var; phase 0 cleared frame, 1 textured mesh, 2 rest of used, 9 never referenced\n')
        fo.write('# callers = function:calls (up to 12); ctx = render categories (render_passes.tsv) whose pass-string functions reach a caller within 4 direct-call levels; reach = a caller is reachable from startup (tier 2 graph)\n')
        fo.write(HDR)
        cols = ['proc', 'group', 'sub', 'phase', 'calls', 'loads', 'nfuncs', 'callers', 'ctx', 'reach', 'varB', 'gotvarA', 'loader_str_xrefs']
        fo.write('\t'.join(cols) + '\n')
        for r in rows:
            fo.write('\t'.join(str(r[c]) for c in cols) + '\n')

    used = [r for r in rows if r['loads']]
    called = [r for r in rows if r['calls']]
    grp = defaultdict(lambda: [0, 0, 0, 0])
    for r in rows:
        g = grp[r['group']]
        g[0] += 1
        g[1] += 1 if r['loads'] else 0
        g[2] += r['calls']
        g[3] += 1 if r['calls'] else 0
    caller_funcs = Counter()
    for r in rows:
        for f in set(callers[r['proc']]) | set(loads[r['proc']]):
            caller_funcs[f] += 1
    # function -> nvn calls count
    fcalls = Counter()
    for f, e in ev.items():
        if e['nvn']:
            fcalls[f] = len(e['nvn'])
    nv_funcs = {f for f, e in ev.items() if e['nvn'] or e['nvn_ld']}
    ctx_funcs = [f for f in nv_funcs if func_cats.get(f)]
    outside = sorted(f for f in nv_funcs if not (0x8f4000 <= f < 0x924000))
    cl_lo = min(f for f in nv_funcs if 0x8f0000 <= f < 0x930000)
    cl_hi = max(f for f in nv_funcs if 0x8f0000 <= f < 0x930000)
    # direct game-code callers of the gfx cluster
    cluster = {f for f in nv_funcs if 0x8f4000 <= f < 0x924000}
    ext_callers = Counter()
    for f in cluster:
        for g in rev.get(f, ()):
            if g not in cluster:
                ext_callers[g] += 1
    never = [r['proc'] for r in rows if not r['loads']]
    md = []
    md.append('# NVN usage census (v262144 main)\n')
    md.append('Static, read-only. Source: `scripts/scope_scan.py` + `scripts/scope_report.py`; table `nvn_usage.tsv`. Module offsets.\n')
    md.append('## Result\n')
    md.append('- 516 procs are resolved by each loader. **%d are used** (loaded from the .bss table at 0x1488db0 by game code): %d with at least one `blr` through the loaded pointer (%d call sites), %d loaded but never called through the tracker (%s). **%d are never referenced** by any function.' % (
        len(used), len(called), sum(r['calls'] for r in rows), len(used) - len(called), ', '.join(r['proc'] for r in used if not r['calls']), len(never)))
    md.append('- Loader A (0x254c40) fills 516 pointer variables reached through GOT slots (0xcca138...). Only `nvnDeviceGetProcAddress` of that table is ever read (0x90d590 and 0x910270, as the argument to loader 0x254c40 and for the second pass); the other 515 variables in table A are never loaded. Table B (0x1488db0..0x1489dd0, filled by 0x90a0c0) carries all real call traffic.')
    md.append('- `nvnBootstrapLoader` is the only real NVN import (three calls in 0x910270). Everything else is `getProcAddress` by name.')
    md.append('- **Key finding:** %d of the %d NVN-touching functions form a compact cluster at 0x%x..0x%x: the statically linked `nn::gfx` NVN backend (0x90d590 is DeviceImpl::Initialize: it calls both loaders, builds the device, then queries `nvnDeviceGetInteger`). Game code reaches it by direct bl (no vtable), so the host can be built either as NVN->Vulkan or by replacing the nn::gfx wrapper functions. %d more functions outside the cluster use NVN procs directly (inlined nn::gfx state setters and helpers): %s. Resolve all of them when hooking at wrapper level.' % (
        len(cluster), len(nv_funcs), cl_lo, cl_hi, len(outside), ', '.join('%#x' % f for f in outside)))
    md.append('- Call counts are static sites, not frequency. Many procs have a single site because nn::gfx funnels all use through one wrapper per API function; the per-frame cost is in `CommandBuffer*` (Bind/Set/Draw).')
    md.append('- Tracker limit: a pointer spilled to the stack and called later would show as a load without `blr` (only the 3 above do).\n')
    md.append('## By NVN object group\n')
    md.append('| group | procs in table | used | called | call sites |\n|---|---|---|---|---|')
    for g, v in sorted(grp.items(), key=lambda x: -x[1][2]):
        md.append('| %s | %d | %d | %d | %d |' % (g, v[0], v[1], v[3], v[2]))
    md.append('')
    md.append('## Top NVN-touching functions\n')
    md.append('| function | NVN call sites | distinct procs | note |\n|---|---|---|---|')
    for f, k in fcalls.most_common(14):
        np_ = sum(1 for r in rows if f in callers[r['proc']])
