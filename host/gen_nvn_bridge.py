"""Generates generated/boot/nvn_bridge.cpp: AArch64-guest -> x86-64-host ABI wrappers for every NVN proc.
Reads the C++ definitions in runtime/nvn/*.cpp (the registered names come from the X(...) tables), classifies each
parameter as integer/pointer (I), float (F) or double (D) and the result as V/U8/U32/U64/F/D, and emits one GuestFn
wrapper per proc plus a name table. Integer args past x7 come from the guest stack. Project tooling, ours.
Usage: python -I host/gen_nvn_bridge.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'runtime' / 'nvn'
OUT = ROOT / 'generated' / 'boot' / 'nvn_bridge.cpp'

files = {p.name: re.sub(r'//[^\n]*', '', p.read_text(encoding='utf-8', errors='replace')) for p in SRC.glob('*.cpp')}
names = []
for fn, t in files.items():
    for m in re.finditer(r'\bX\((\w+)\)', t):
        if m.group(1) not in names:
            names.append(m.group(1))
alias = {'CommandHandle': 'U64', 'TextureHandle': 'U64', 'Boolean': 'U8', 'GenericProc': 'U64'}


def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '(<[': depth += 1
        if ch in ')>]': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out


def kind(ty):
    ty = ty.strip()
    if '*' in ty or '&' in ty: return 'I'
    if re.search(r'\bdouble\b', ty): return 'D'
    if re.search(r'\bfloat\b', ty): return 'F'
    return 'I'


def rkind(ty):
    ty = ty.replace('static', '').replace('inline', '').replace('const', '').strip()
    if ty == 'void': return 'V'
    if '*' in ty: return 'U64'
    if ty in alias: return alias[ty]
    if ty == 'float': return 'F'
    if ty == 'double': return 'D'
    if ty in ('bool', 'uint8_t', 'Boolean'): return 'U8'
    if ty in ('int', 'unsigned', 'uint32_t', 'int32_t', 'unsigned int', 'uint16_t', 'int16_t'): return 'U32'
    return 'U64'


sigs, bad = {}, []
for n in names:
    found = None
    for fn, t in files.items():
        for m in re.finditer(r'(?m)^[ \t]*([A-Za-z_][\w:<>\*&\s]*?)([ \t\*&]+)' + n + r'\s*\(([^;{)]*(?:\([^)]*\)[^;{)]*)*)\)\s*(?:const\s*)?\{', t):
            # the separator can hold the star of a pointer result type (`void* BufferMap(...)`): keep it, or the result is dropped as void
            found = (m.group(1) + ''.join(ch for ch in m.group(2) if ch in '*&'), m.group(3)); break
        if found: break
    if not found:
        bad.append(n); continue
    rt, ps = found
    ps = [p for p in split_params(ps) if p != 'void']
    # a function-pointer parameter or a by-value struct is not handled: flag
    ks = [kind(p) for p in ps]
    for p in ps:
        if '*' not in p and '&' not in p and not re.search(r'\b(float|double|int|unsigned|size_t|ptrdiff_t|uint\w+|int\w+|bool|Boolean|TextureHandle|CommandHandle|void)\b', p) and not re.match(r'^(const\s+)?[A-Z]\w*\s+\w*$', p):
            bad.append(n + ' ?param ' + p)
    # by-value non-scalar types (CamelCase types that are enums are fine: NVN enums are ints) -> I
    sigs[n] = (rkind(rt), ks, rt.strip(), ps)

if bad:
    print('UNPARSED:', bad, file=sys.stderr)
L = ['// Generated by host/gen_nvn_bridge.py. Do not edit.', '#include "loader.h"', '#include "nvn/nvn_host.h"', '#include <cstring>', '#include <string>', '#include <unordered_map>', '#include <cstdlib>', '',
     'extern "C" { void (*nvnBootstrapLoader(const char *name))(void); }',
     'extern "C" { void os_host_block_begin(void); void os_host_block_end(void); }',
     'namespace nvnbridge {', 'typedef uint64_t u64;', 'static inline u64 sarg(Cpu *c, int i) { return ((u64 *)c->sp)[i]; }',
     "static const bool kReleaseCore = getenv(\"SNAP_NVN_RELEASE_CORE\") != nullptr;   // see BLOCKING in host/gen_nvn_bridge.py",
     'struct BlockScope { BlockScope() { if (kReleaseCore) os_host_block_begin(); } ~BlockScope() { if (kReleaseCore) os_host_block_end(); } };', '']
BLOCKING = {'QueueSubmitCommands', 'QueuePresentTexture', 'QueueFinish', 'SyncWait', 'WindowAcquireTexture'}
for n, (rk, ks, rt, ps) in sigs.items():
    args, ni, nf, ns = [], 0, 0, 0
    for k in ks:
        if k == 'I':
            if ni < 8: args.append(f'c->x[{ni}]')
            else: args.append(f'sarg(c,{ns})'); ns += 1
            ni += 1
        else:
            ty = 'float' if k == 'F' else 'double'
            args.append(f'*({ty}*)&c->v[{nf}]'); nf += 1
    ptys = ', '.join({'I': 'u64', 'F': 'float', 'D': 'double'}[k] for k in ks)
    rty = {'V': 'void', 'U8': 'uint8_t', 'U32': 'uint32_t', 'U64': 'u64', 'F': 'float', 'D': 'double'}[rk]
    call = f'F({", ".join(args)})'
    if n == 'DeviceGetProcAddress':
        body = 'c->x[0] = lookup_thunk((const char *)c->x[1]);'
    elif rk == 'V': body = call + ';'
    elif rk == 'F': body = f'float r = {call}; c->v[0] = 0; memcpy(&c->v[0], &r, 4);'
    elif rk == 'D': body = f'double r = {call}; c->v[0] = 0; memcpy(&c->v[0], &r, 8);'
    else: body = f'c->x[0] = (u64){call};'
    fp = f'static {rty}(*F)({ptys}) = ({rty}(*)({ptys}))nvnBootstrapLoader("nvn{n}"); '
    if n != 'DeviceGetProcAddress': body = fp + body
    if n == 'TextureInitialize': body = 'nvnHostSetGuestFrame(c->x[29], c->x[30]); ' + body   # call-site scale exemptions (nvn_host.h)
    # perf pass 3: host-side work that is GPU work or a kernel wait on the Switch (command replay, present + frame limiter,
    # fence waits, swapchain acquire) gives the calling thread's virtual core back, so threads pinned to that core
    # (ResourceUncompress, loaders) are not starved for the whole replay/pace/GPU wait. Opt-in, SNAP_NVN_RELEASE_CORE=1: on an
    # exclusive Florio bench it did not help (course 1% low 11.3 vs 16.8 fps held, analysis/perf/results.md "Scene 2"); it only
    # helped on a CPU-saturated PC. Default = hold the core (unchanged behavior).
    if n in BLOCKING: body = 'BlockScope bs; ' + body
    L.append(f'static void br_{n}(Cpu *c) {{ {body} }}   // {rt}({", ".join(ps)})')
L.append('')
L.append('struct E { const char *name; GuestFn fn; };')
L.append('static const E kBridge[] = {')
for n in sigs: L.append(f'    {{"nvn{n}", br_{n}}},')
L.append('};')
L.append('''
static std::unordered_map<std::string, uint64_t> g_thunks;
uint64_t lookup_thunk(const char *name) {
    if (!name) return 0;
    auto it = g_thunks.find(name);
    if (it != g_thunks.end()) return it->second;
    for (auto &e : kBridge) if (!strcmp(e.name, name)) {
        uint64_t a = loader::add_override(std::string("nvnproc:") + name, e.fn)->addr;
        g_thunks[name] = a;
        return a;
    }
    // not in the NVN layer's table: debugger/NVX extensions are accepted as no-ops (returns 0); anything else is a
    // logging abort when it is called, so the owner of runtime/nvn sees exactly which proc is missing
    bool noop = strstr(name, "NVX") || strstr(name, "Debugger");
    if (noop) fprintf(stderr, "nvn: proc %s is an NVX/debugger extension: no-op stub\\n", name);
    uint64_t a = noop ? loader::add_override(std::string("nvnproc:") + name, [](Cpu *c) { c->x[0] = 0; })->addr
        : loader::add_stub(std::string("nvnproc:") + name, [](Cpu *c, Thunk *t) { fprintf(stderr, "nvn: unregistered proc %s called, caller %#llx\\n", t->name.c_str() + 8, (unsigned long long)c->x[30]); fflush(stderr); abort(); })->addr;
    g_thunks[name] = a;
    return a;
}
static void bootstrap_loader(Cpu *c) { c->x[0] = lookup_thunk((const char *)c->x[0]); }
}  // namespace nvnbridge

void snap_bind_nvn() { loader::add_override("nvnBootstrapLoader", nvnbridge::bootstrap_loader); }
int snap_nvn_bridge_count() { return (int)(sizeof nvnbridge::kBridge / sizeof *nvnbridge::kBridge); }
''')
# lookup_thunk is used before its definition in br_DeviceGetProcAddress
txt = '\n'.join(L)
txt = txt.replace('typedef uint64_t u64;', 'typedef uint64_t u64;\nuint64_t lookup_thunk(const char *name);')
txt = txt.replace('#include <cstring>', '#include <cstring>\n#include <cstdio>')
OUT.parent.mkdir(parents=True, exist_ok=True)
if not OUT.exists() or OUT.read_text(encoding='utf-8') != txt:   # unchanged: skip the write (parallel worker builds share this file)
    OUT.write_text(txt, encoding='utf-8')
print(f'{len(sigs)} of {len(names)} procs bridged -> {OUT}')
