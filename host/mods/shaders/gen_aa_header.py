# Generates runtime/nvn/nvn_aa_spv.h (SPIR-V of the SMAA/CAS shaders and the SMAA lookup textures). Run via build_aa_shaders.ps1.
import os, re, subprocess, struct, sys
root = sys.argv[1]
here = os.path.join(root, 'host', 'mods', 'shaders')
ref = os.path.join(root, 'build', 'smaa_ref')
dxc = os.path.join(root, 'tools', 'vulkan_sdk', 'Bin', 'dxc.exe')
tmp = os.path.join(root, 'build', 'smaa_ref', 'spv'); os.makedirs(tmp, exist_ok=True)
jobs = [('smaa_aa.hlsl', 'vs_edge', 'vs', 'smaa_vs_edge'), ('smaa_aa.hlsl', 'ps_edge', 'ps', 'smaa_ps_edge'),
        ('smaa_aa.hlsl', 'vs_weights', 'vs', 'smaa_vs_weights'), ('smaa_aa.hlsl', 'ps_weights', 'ps', 'smaa_ps_weights'),
        ('smaa_aa.hlsl', 'vs_blend', 'vs', 'smaa_vs_blend'), ('smaa_aa.hlsl', 'ps_blend', 'ps', 'smaa_ps_blend'),
        ('cas.hlsl', 'vs_cas', 'vs', 'cas_vs'), ('cas.hlsl', 'ps_cas', 'ps', 'cas_ps')]
out = ['// Generated by host/mods/shaders/gen_aa_header.py. SMAA code: Copyright (C) 2013 Jorge Jimenez, Jose I. Echevarria, Belen Masia, Fernando Navarro,',
       '// Diego Gutierrez (MIT, see THIRD_PARTY_NOTICES.md). CAS: AMD FidelityFX algorithm (MIT). Do not edit.', '#pragma once', '#include <cstdint>', '']
for f, entry, st, name in jobs:
    spv = os.path.join(tmp, name + '.spv')
    r = subprocess.run([dxc, '-spirv', '-fspv-target-env=vulkan1.1', '-fspv-entrypoint-name=main', '-T', st + '_6_0', '-E', entry, '-I', ref, '-Fo', spv, os.path.join(here, f)], capture_output=True, text=True)
    if r.returncode: print(r.stdout, r.stderr); sys.exit(1)
    b = open(spv, 'rb').read()
    w = struct.unpack('<%dI' % (len(b) // 4), b)
    out.append('static const uint32_t k_%s[%d] = {%s};' % (name, len(w), ','.join('0x%x' % x for x in w)))
def arr(path, label):
    t = open(path).read()
    t = t[t.index('{') + 1:t.rindex('}')]
    v = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]{2}', t)]
    return v
area = arr(os.path.join(ref, 'area_out.txt'), 'area'); search = arr(os.path.join(ref, 'search_out.txt'), 'search')
assert len(area) == 160 * 560 * 2, len(area)
assert len(search) == 64 * 16, len(search)
out.append('static const uint8_t k_smaa_area[%d] = {%s};' % (len(area), ','.join(str(x) for x in area)))
out.append('static const uint8_t k_smaa_search[%d] = {%s};' % (len(search), ','.join(str(x) for x in search)))
open(os.path.join(root, 'runtime', 'nvn', 'nvn_aa_spv.h'), 'w').write('\n'.join(out) + '\n')
print('wrote nvn_aa_spv.h', len(area), len(search))
