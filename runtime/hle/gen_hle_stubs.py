"""Builds analysis/runtime/hle_coverage.tsv and generated/hle_unimplemented.cpp.

Input : analysis/runtime/imports_usage.tsv (the 731 imports of `main`), and the HLE_IMPL / HLE_NOOP registration lines
        in runtime/hle/*.cpp and *.inc.
Output: hle_coverage.tsv        one row per import (status: implemented, lifted-pure-software, stub-noop, todo)
                                plus rows for overrides of sdk-internal symbols that are not `main` imports
        generated/hle_unimplemented.cpp   one logging "not implemented" stub per leftover nn:: import this layer owns
                                (an nn:: import with no override logs name, caller and arguments, then aborts)
Run:    python gen_hle_stubs.py [--all]   (--all also stubs the os / audio / nvn imports owned by other layers)
Never edit the outputs by hand.
"""
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
HLE = os.path.join(ROOT, 'runtime', 'hle')

# service (imports_usage column 3) -> (status, owner, note) for imports that have no HLE registration
LIFTED = {
    'libc': 'sdk libc is lifted guest code; linker/DSO symbols are host data (loader)',
    'libc++': 'sdk libc++ is lifted guest code',
    'libc++abi': 'sdk libc++abi is lifted guest code',
    'util': 'nn::util: pure software, no IPC',
    'fontll': 'nn::fontll: pure software, no IPC',
    'image': 'nn::image JPEG: pure software, no IPC',
    'mem': 'nn::mem: pure software, no IPC',
    'result': 'nn::result: pure software',
    'swkbd': 'swkbd argument builders: pure software (ShowKeyboard is overridden)',
    'crypto': 'nn::crypto AES/MD5/SHA1: pure software (random bytes is overridden)',
    'vdk': 'weak data symbol: resolves to null',
    'other': 'weak symbol: resolves to null',
}
# data objects the sdk defines itself (STT_OBJECT in v262144-sdk.elf .dynsym): lifted with the sdk, not functions to stub
LIFTED_DATA = {'_ZN2nn3hid13VibrationNode30DefaultVibrationSampleIntervalE': 'sdk-defined constant (STT_OBJECT)'}
OTHER_OWNER = {'os': 'runtime/os', 'audio': 'runtime/audio', 'nvn': 'runtime/nvn'}


def registrations():
    reg = {}
    pat = re.compile(r'HLE_(IMPL|NOOP)\("(\w+)",\s*"([^"]+)",\s*(\w+)\)')
    files = sorted(glob.glob(os.path.join(HLE, '*.cpp')) + glob.glob(os.path.join(HLE, '*.inc')))
    for f in files:
        for m in pat.finditer(open(f, encoding='utf8').read()):
            kind, svc, sym, fn = m.groups()
            reg[sym] = ('implemented' if kind == 'IMPL' else 'stub-noop', svc, os.path.basename(f), fn)
    return reg


def imports():
    rows = []
    for l in open(os.path.join(ROOT, 'analysis', 'runtime', 'imports_usage.tsv'), encoding='utf8'):
        if l.startswith('#') or l.startswith('name\t'):
            continue
        p = l.rstrip('\n').split('\t')
        rows.append(dict(name=p[0], dem=p[1], svc=p[2], boot1=p[10], order=p[11], boot2=p[15]))
    return rows


def main():
    reg = registrations()
    imps = imports()
    names = {r['name'] for r in imps}
    out = []
    stubs = []
    counts = {}
    for r in imps:
        n = r['name']
        if n in reg:
            st, svc, src, fn = reg[n]
            owner, note = 'runtime/hle', '%s:%s' % (src, fn)
        elif n in LIFTED_DATA:
            st, owner, note = 'lifted-pure-software', 'lifted', LIFTED_DATA[n]
        elif r['svc'] in LIFTED:
            st, owner, note = 'lifted-pure-software', 'lifted', LIFTED[r['svc']]
        elif r['svc'] in OTHER_OWNER:
            st, owner, note = 'todo', OTHER_OWNER[r['svc']], 'owned by another layer'
        else:
            st, owner, note = 'todo', 'runtime/hle', 'no override: generated stub logs and aborts'
        counts[st] = counts.get(st, 0) + 1
        boot = 'yes' if r['boot1'] == 'yes' else ('maybe' if r['boot2'] == 'yes' else 'no')
        out.append((st, r['svc'], owner, boot, r['order'], n, r['dem'], note))
        if st == 'todo' and (owner == 'runtime/hle' or '--all' in sys.argv):
            stubs.append(n)
    extra = 0
    for sym, (st, svc, src, fn) in sorted(reg.items()):
        if sym not in names:
            out.append((st, svc, 'runtime/hle', 'n/a', '', sym, sym, 'not a main import (sdk-internal or alias): %s:%s' % (src, fn)))
            extra += 1
    out.sort(key=lambda t: (['implemented', 'stub-noop', 'todo', 'lifted-pure-software'].index(t[0]), t[1], t[5]))
    p = os.path.join(ROOT, 'analysis', 'runtime', 'hle_coverage.tsv')
    with open(p, 'w', encoding='utf8', newline='\n') as f:
        f.write('# file: hle_coverage.tsv\n')
        f.write('# generated by runtime/hle/gen_hle_stubs.py from imports_usage.tsv and the HLE_IMPL/HLE_NOOP registrations; do not edit\n')
        f.write('# one row per import of main (731) plus %d override rows for symbols that are not main imports (boot = n/a)\n' % extra)
        f.write('# status: implemented | lifted-pure-software | stub-noop | todo. todo with owner runtime/os, runtime/audio, runtime/nvn belongs to that layer\n')
        f.write('# boot: yes = reachable from the boot entry points over direct calls (imports_usage boot1), maybe = only via address-taken functions (boot2)\n')
        f.write('status\tservice\towner\tboot\tboot_order\tname\tdemangled\tnote\n')
        for t in out:
            f.write('\t'.join(t) + '\n')
    print(p, counts, 'extra override rows:', extra)

    os.makedirs(os.path.join(ROOT, 'generated'), exist_ok=True)
    gp = os.path.join(ROOT, 'generated', 'hle_unimplemented.cpp')
    with open(gp, 'w', encoding='utf8', newline='\n') as f:
        f.write('// SPDX-License-Identifier: MIT\n// Generated by runtime/hle/gen_hle_stubs.py; do not edit. One stub per nn:: import without an override.\n')
        f.write('#include "../runtime/hle/hle.h"\n\nnamespace {\n')
        for i, n in enumerate(stubs):
            f.write('void stub_%d(Cpu* c) { hle::unimplemented(c, "%s"); }\n' % (i, n))
        f.write('const hle::StubEntry kStubs[] = {\n')
        for i, n in enumerate(stubs):
            f.write('  {"%s", stub_%d},\n' % (n, i))
        f.write('  {nullptr, nullptr}};\n')
        f.write('struct Install { Install() { hle::set_generated_stubs(kStubs, sizeof kStubs / sizeof kStubs[0] - 1); } } g_install;\n}  // namespace\n')
    print(gp, len(stubs), 'stubs')


main()
