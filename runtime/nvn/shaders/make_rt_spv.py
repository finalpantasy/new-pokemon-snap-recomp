# Regenerates ../nvn_rt_spv.h from rt_conv.comp, rt_ovl.vert, rt_ovl.frag (glslangValidator from tools/vulkan_sdk). Run: python -I make_rt_spv.py
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_rt_spv.py from shaders/rt_conv.comp, rt_ovl.vert, rt_ovl.frag (ray tracing capture conversion and debug overlay). No game data.', '#pragma once', '#include <cstdint>', 'namespace snap_rt {']
for src, name in (('rt_conv.comp', 'kRtConvSpv'), ('rt_ovl.vert', 'kRtOvlVertSpv'), ('rt_ovl.frag', 'kRtOvlFragSpv')):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', '--target-env', 'vulkan1.3', str(here / src), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        w = struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())
    out.append(f'static const uint32_t {name}[] = {{' + ','.join(hex(x) for x in w) + '};')
out.append('}  // namespace snap_rt')
(here.parent / 'nvn_rt_spv.h').write_text('\n'.join(out) + '\n')
