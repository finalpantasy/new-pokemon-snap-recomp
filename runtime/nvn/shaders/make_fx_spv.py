# Regenerates ../nvn_fx_spv.h and ../nvn_contact_spv.h (glslangValidator from tools/vulkan_sdk). Run: python -I make_fx_spv.py
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'


def words(src, stage):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', '-S', stage, str(here / src), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        return struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())


def emit(path, desc, items):
    out = ['// SPDX-License-Identifier: MIT', f'// Generated by shaders/make_fx_spv.py from {desc}. Our own code, no game data.', '#pragma once', '#include <cstdint>']
    for name, src, stage in items:
        out.append(f'static const uint32_t {name}[] = {{' + ','.join(hex(x) for x in words(src, stage)) + '};')
    pathlib.Path(path).write_text('\n'.join(out) + '\n')


emit(here.parent / 'nvn_fx_spv.h', 'fx_fullscreen.vert', [('kFxFullscreenVert', 'fx_fullscreen.vert', 'vert')])
if (here / 'contact.frag').exists():
    emit(here.parent / 'nvn_contact_spv.h', 'contact.frag', [('kContactFrag', 'contact.frag', 'frag')])
