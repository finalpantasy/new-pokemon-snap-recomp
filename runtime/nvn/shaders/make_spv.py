# Regenerates ../nvn_hdr_spv.h from hdr.vert / hdr.frag (glslangValidator from tools/vulkan_sdk). Run: python -I make_spv.py
import pathlib, struct, subprocess, sys, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_spv.py from shaders/hdr.vert|frag (HDR10 present pass). No game data.', '#pragma once', '#include <cstdint>', 'namespace snap_hdr {']
for stage, name in (('vert', 'kHdrVertSpv'), ('frag', 'kHdrFragSpv')):
    with tempfile.TemporaryDirectory() as t:
        o = pathlib.Path(t) / 'o.spv'
        subprocess.run([str(g), '-V', str(here / f'hdr.{stage}'), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
        w = struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())
    out.append(f'static const uint32_t {name}[] = {{' + ','.join(hex(x) for x in w) + '};')
out.append('}  // namespace snap_hdr')
(here.parent / 'nvn_hdr_spv.h').write_text('\n'.join(out) + '\n')
