# Regenerates ../nvn_gtao_spv.h from gtao.frag (glslangValidator from tools/vulkan_sdk). Run: python -I make_gtao_spv.py
import pathlib, struct, subprocess, tempfile
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
g = root / 'tools' / 'vulkan_sdk' / 'Bin' / 'glslangValidator.exe'
with tempfile.TemporaryDirectory() as t:
    o = pathlib.Path(t) / 'o.spv'
    subprocess.run([str(g), '-V', '-S', 'frag', str(here / 'gtao.frag'), '-o', str(o)], check=True, stdout=subprocess.DEVNULL)
    w = struct.unpack('<%dI' % (o.stat().st_size // 4), o.read_bytes())
out = ['// SPDX-License-Identifier: MIT', '// Generated by shaders/make_gtao_spv.py from gtao.frag (GTAO replacement of the HBAO fragment program). Our own code, no game data.',
       '#pragma once', '#include <cstdint>', 'static const uint32_t kGtaoFrag[] = {' + ','.join(hex(x) for x in w) + '};']
(here.parent / 'nvn_gtao_spv.h').write_text('\n'.join(out) + '\n')
